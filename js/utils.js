/* ── Currency formatting ──────────────────────────────────── */

const currencyFormatter = new Intl.NumberFormat('en-IN', {
  style: 'currency',
  currency: 'INR',
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

/**
 * Format a numeric amount as ₹ INR currency string.
 * @param {number} amount
 * @returns {string} e.g. "₹1,245.30"
 */
export function formatCurrency(amount) {
  if (typeof amount !== 'number' || !isFinite(amount)) return '₹0.00';
  return currencyFormatter.format(amount);
}

/**
 * Format a currency amount in a compact way (₹1.2K, ₹10K, ₹1L, ₹1Cr).
 * @param {number} amount
 * @returns {string}
 */
export function formatCurrencyCompact(amount) {
  if (typeof amount !== 'number' || !isFinite(amount)) return '₹0';
  if (amount >= 10000000) return `₹${(amount / 10000000).toFixed(1)}Cr`;
  if (amount >= 100000) return `₹${(amount / 100000).toFixed(1)}L`;
  if (amount >= 1000) return `₹${(amount / 1000).toFixed(1)}K`;
  return `₹${amount.toFixed(0)}`;
}

/* ── Date formatting ──────────────────────────────────────── */

/**
 * Format a YYYY-MM-DD string to a readable date.
 * @param {string} dateStr - "2026-10-04"
 * @returns {string} e.g. "Oct 4, 2026"
 */
export function formatDate(dateStr) {
  if (!dateStr) return '';
  const d = new Date(dateStr + 'T00:00:00');
  if (isNaN(d.getTime())) return dateStr;
  return d.toLocaleDateString('en-IN', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });
}

/**
 * Format a YYYY-MM-DD string to a short date.
 * @param {string} dateStr
 * @returns {string} e.g. "04 Oct"
 */
export function formatDateShort(dateStr) {
  if (!dateStr) return '';
  const d = new Date(dateStr + 'T00:00:00');
  if (isNaN(d.getTime())) return dateStr;
  return d.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
  });
}

/**
 * Get a month label from year and month number.
 * @param {number} year
 * @param {number} month - 0-indexed
 * @returns {string} e.g. "Oct 2026"
 */
export function getMonthLabel(year, month) {
  const d = new Date(year, month, 1);
  return d.toLocaleDateString('en-IN', { month: 'short', year: 'numeric' });
}

/**
 * Get a short month label.
 * @param {number} month - 0-indexed
 * @returns {string} e.g. "Oct"
 */
export function getMonthShortLabel(month) {
  const months = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
  return months[month] || '';
}

/* ── Date helpers ─────────────────────────────────────────── */

/**
 * Get the current year and month.
 * @returns {{ year: number, month: number }}
 */
export function getCurrentMonth() {
  const now = new Date();
  return { year: now.getFullYear(), month: now.getMonth() };
}

/**
 * Get today's date as YYYY-MM-DD.
 * @returns {string}
 */
export function getTodayString() {
  const now = new Date();
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
}

/**
 * Validate whether a string is a valid YYYY-MM-DD date.
 * @param {string} dateStr
 * @returns {boolean}
 */
export function isValidDate(dateStr) {
  if (!dateStr || typeof dateStr !== 'string') return false;
  const match = dateStr.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return false;
  const [, y, m, d] = match.map(Number);
  const date = new Date(y, m - 1, d);
  return (
    date.getFullYear() === y &&
    date.getMonth() === m - 1 &&
    date.getDate() === d
  );
}

/* ── Percentage formatting ────────────────────────────────── */

/**
 * Format a value as a percentage string.
 * @param {number} value - 0 to 100
 * @returns {string} e.g. "42.5%"
 */
export function formatPercentage(value) {
  if (typeof value !== 'number' || !isFinite(value)) return '0%';
  return `${value.toFixed(1)}%`;
}

/* ── ID generation ────────────────────────────────────────── */

/**
 * Generate a unique ID.
 * Uses crypto.randomUUID() when available, falls back to timestamp + random.
 * @returns {string}
 */
export function generateId() {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  return `${Date.now()}-${Math.random().toString(36).substring(2, 11)}`;
}

/* ── Debounce ─────────────────────────────────────────────── */

/**
 * Debounce a function call.
 * @param {Function} fn
 * @param {number} delay - milliseconds
 * @returns {Function}
 */
export function debounce(fn, delay = 300) {
  let timer;
  return function (...args) {
    clearTimeout(timer);
    timer = setTimeout(() => fn.apply(this, args), delay);
  };
}

